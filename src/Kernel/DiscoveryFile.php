<?php

declare(strict_types=1);

namespace TMSWP\Core\Kernel;

use Throwable;
use TMSWP\Core\Block\DiscoveredBlock;
use TMSWP\Core\Exception\DiscoveryException;

/**
 * 探索結果ファイル(KernelConfig::discoveryFile())の生成と読み込み。
 *
 * ファイルは `wp tmswp discover` が生成し、コードと一緒にコミット・デプロイする。内容は環境に依存しない
 * (絶対パス・mtime・生成時刻を含まない)ため、どの環境で生成してもバイト単位で同一になる。
 */
final class DiscoveryFile
{
    public const SCHEMA_VERSION = 5;

    private const REGENERATE_HINT = "regenerate it with 'wp tmswp discover' and deploy it together with the code";

    public function __construct(
        private readonly KernelConfig $config,
    ) {}

    public function path(): string
    {
        return $this->config->discoveryFile();
    }

    /**
     * 探索結果ファイルを読み込む。ファイルが無い・壊れている・この Kernel の構成と合わない場合は例外を投げる。
     *
     * @throws DiscoveryException
     */
    public function load(): DiscoveryResult
    {
        $path = $this->path();

        if (!is_file($path)) {
            throw $this->invalid('discovery file not found');
        }

        try {
            $payload = (static fn(string $file): mixed => include $file)($path);
        } catch (Throwable $exception) {
            throw $this->invalid("failed to include discovery file: {$exception->getMessage()}", $exception);
        }

        if (!\is_array($payload)) {
            throw $this->invalid('discovery file must return an array');
        }

        if (($payload['schema'] ?? null) !== self::SCHEMA_VERSION) {
            throw $this->invalid('discovery file schema mismatch (expected ' . self::SCHEMA_VERSION . ')');
        }

        if (($payload['appNamespace'] ?? null) !== $this->config->appNamespace) {
            throw $this->invalid("discovery file was generated for another app namespace (expected '{$this->config->appNamespace}')");
        }

        $appDir = $payload['appDir'] ?? null;

        if (!\is_string($appDir) || $appDir === '' || realpath(\dirname($path) . '/' . $appDir) !== $this->config->appDir) {
            throw $this->invalid("discovery file was generated for another app directory (expected '{$this->config->appDir}')");
        }

        return new DiscoveryResult(
            array_map($this->component(...), $this->entries($payload, 'components')),
            array_map($this->hookMethod(...), $this->entries($payload, 'hookMethods')),
            array_map($this->block(...), $this->entries($payload, 'blocks')),
        );
    }

    /** 探索結果をファイルの内容(PHP コード)にする。同じ探索結果からは常に同じバイト列を返す。 */
    public function render(DiscoveryResult $result): string
    {
        $payload = [
            'schema' => self::SCHEMA_VERSION,
            'appNamespace' => $this->config->appNamespace,
            // ファイルの置き場は appDir の親ディレクトリに固定しているため、相対パスは appDir のディレクトリ名になる
            'appDir' => basename($this->config->appDir),
            'components' => array_map(
                static fn(DiscoveredComponent $component): array => [
                    'class' => $component->class,
                    'attributeClass' => $component->attributeClass,
                    'attributeArguments' => $component->attributeArguments,
                ],
                $result->components,
            ),
            'hookMethods' => array_map(
                static fn(DiscoveredHookMethod $hookMethod): array => [
                    'class' => $hookMethod->class,
                    'method' => $hookMethod->method,
                    'hook' => $hookMethod->hook,
                    'priority' => $hookMethod->priority,
                    'acceptedArgs' => $hookMethod->acceptedArgs,
                    'kind' => $hookMethod->kind->value,
                ],
                $result->hookMethods,
            ),
            'blocks' => array_map(
                static fn(DiscoveredBlock $block): array => [
                    'name' => $block->name,
                    'path' => $block->path,
                    'metadataHash' => $block->metadataHash,
                ],
                $result->blocks,
            ),
        ];

        return "<?php\n\n// @generated by 'wp tmswp discover'. Do not edit.\n\ndeclare(strict_types=1);\n\nreturn " . $this->export($payload, 0) . ";\n";
    }

    /** ファイルの内容が探索結果と一致するか。ファイルが無ければ false。 */
    public function isUpToDate(DiscoveryResult $result): bool
    {
        $path = $this->path();

        if (!is_file($path)) {
            return false;
        }

        $contents = file_get_contents($path);

        if ($contents === false) {
            throw new DiscoveryException("failed to read discovery file: {$path}");
        }

        return $contents === $this->render($result);
    }

    /**
     * 探索結果をファイルに書く。一時ファイルに書いてから rename で置き換える。
     *
     * @throws DiscoveryException 書き込みに失敗した場合
     */
    public function write(DiscoveryResult $result): void
    {
        $path = $this->path();
        $contents = $this->render($result);
        $tmp = $path . '.' . uniqid('', true) . '.tmp';

        if (file_put_contents($tmp, $contents) !== \strlen($contents)) {
            $this->removeTemporaryFile($tmp);

            throw new DiscoveryException("failed to write discovery file: {$tmp}");
        }

        if (!rename($tmp, $path)) {
            $this->removeTemporaryFile($tmp);

            throw new DiscoveryException("failed to replace discovery file: {$path}");
        }

        if (\function_exists('opcache_invalidate')) {
            opcache_invalidate($path, true);
        }
    }

    /**
     * 値を PHP のコードにする。配列は短縮構文で書き、値(スカラー・enum)は var_export() に任せる。
     * var_export() の配列の出力は行末に空白を残し、空白を削るエディタで内容が変わってしまうため使わない。
     */
    private function export(mixed $value, int $depth): string
    {
        if ($value === null) {
            return 'null';
        }

        if (!\is_array($value)) {
            return var_export($value, true);
        }

        if ($value === []) {
            return '[]';
        }

        $indent = str_repeat('    ', $depth + 1);
        $isList = array_is_list($value);
        $lines = [];

        foreach ($value as $key => $entry) {
            $lines[] = $indent . ($isList ? '' : var_export($key, true) . ' => ') . $this->export($entry, $depth + 1) . ',';
        }

        return "[\n" . implode("\n", $lines) . "\n" . str_repeat('    ', $depth) . ']';
    }

    private function removeTemporaryFile(string $tmp): void
    {
        if (is_file($tmp) && !unlink($tmp)) {
            throw new DiscoveryException("failed to remove temporary discovery file: {$tmp}");
        }
    }

    private function invalid(string $reason, ?Throwable $previous = null): DiscoveryException
    {
        return new DiscoveryException("{$reason}: {$this->path()}; " . self::REGENERATE_HINT, previous: $previous);
    }

    /**
     * @param array<mixed> $payload
     *
     * @return list<array<mixed>>
     */
    private function entries(array $payload, string $key): array
    {
        $entries = $payload[$key] ?? null;

        if (!\is_array($entries) || !array_is_list($entries)) {
            throw $this->invalid("discovery file entry '{$key}' must be a list");
        }

        $list = [];

        foreach ($entries as $entry) {
            if (!\is_array($entry)) {
                throw $this->invalid("discovery file entry '{$key}' must contain arrays");
            }

            $list[] = $entry;
        }

        return $list;
    }

    /** @param array<mixed> $entry */
    private function component(array $entry): DiscoveredComponent
    {
        $arguments = $entry['attributeArguments'] ?? null;

        if (!\is_array($arguments)) {
            throw $this->invalid('discovery file component entry has invalid attributeArguments');
        }

        return new DiscoveredComponent(
            $this->nonEmptyString($entry, 'class', 'components'),
            $this->nonEmptyString($entry, 'attributeClass', 'components'),
            $arguments,
        );
    }

    /** @param array<mixed> $entry */
    private function hookMethod(array $entry): DiscoveredHookMethod
    {
        $priority = $entry['priority'] ?? null;
        $acceptedArgs = $entry['acceptedArgs'] ?? null;

        if (!\is_int($priority) || !\is_int($acceptedArgs)) {
            throw $this->invalid('discovery file hookMethods entry has invalid priority or acceptedArgs');
        }

        $kind = $entry['kind'] ?? null;
        $kind = \is_string($kind) ? HookMethodKind::tryFrom($kind) : null;

        if ($kind === null) {
            throw $this->invalid("discovery file hookMethods entry has invalid 'kind'");
        }

        return new DiscoveredHookMethod(
            $this->nonEmptyString($entry, 'class', 'hookMethods'),
            $this->nonEmptyString($entry, 'method', 'hookMethods'),
            $this->nonEmptyString($entry, 'hook', 'hookMethods'),
            $priority,
            $acceptedArgs,
            $kind,
        );
    }

    /** @param array<mixed> $entry */
    private function block(array $entry): DiscoveredBlock
    {
        return new DiscoveredBlock(
            $this->nonEmptyString($entry, 'name', 'blocks'),
            $this->nonEmptyString($entry, 'path', 'blocks'),
            $this->nonEmptyString($entry, 'metadataHash', 'blocks'),
        );
    }

    /**
     * @param array<mixed> $entry
     *
     * @return non-empty-string
     */
    private function nonEmptyString(array $entry, string $key, string $section): string
    {
        $value = $entry[$key] ?? null;

        if (!\is_string($value) || $value === '') {
            throw $this->invalid("discovery file {$section} entry has invalid '{$key}'");
        }

        return $value;
    }
}
